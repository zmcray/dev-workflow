#!/usr/bin/env bash
# PreToolUse hook (matcher Write|Edit|MultiEdit), installed once per Mac. Blocks two mistakes:
#   1. A Write that would create a new date-first file. Editing or overwriting a file that already
#      exists is allowed, so legacy names never block work.
#   2. A Write or Edit to a *.pbxproj in a repo whose root has project.yml: XcodeGen generates that
#      file, so a hand edit is lost on the next generate.
GUARD="$(cd "$(dirname "$0")/.." && pwd)/scripts/guards/date-last-names.mjs"
exec node - "$GUARD" 3<&0 <<'NODE'
const fs = require('node:fs')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const payload = JSON.parse(fs.readFileSync(3, 'utf8'))
const file = payload.tool_input?.file_path
if (typeof file !== 'string' || !['Write', 'Edit', 'MultiEdit'].includes(payload.tool_name)) process.exit(0)
const absolute = path.resolve(payload.cwd || process.cwd(), file)

if (absolute.endsWith('.pbxproj')) {
  // The repo root is the nearest folder above the file that holds .git (a folder, or a file in a worktree).
  let dir = path.dirname(absolute)
  while (!fs.existsSync(path.join(dir, '.git')) && path.dirname(dir) !== dir) dir = path.dirname(dir)
  if (fs.existsSync(path.join(dir, '.git')) && fs.existsSync(path.join(dir, 'project.yml'))) {
    process.stderr.write(`${file} is generated by XcodeGen from ${path.join(dir, 'project.yml')}. ` +
      'Edit project.yml instead, then regenerate the project (xcodegen generate, or the repo\'s scripts/xcodegen.sh).\n')
    process.exit(2)
  }
}

if (payload.tool_name !== 'Write' || fs.existsSync(absolute)) process.exit(0)
const result = spawnSync(process.execPath, [process.argv[2], '--paths', file], { encoding: 'utf8' })
if (result.status === 1) {
  process.stderr.write(result.stderr)
  process.exit(2)
}
process.exit(0)
NODE
